// 把 kill-app-tree.ps1 转成 NSIS 可内联的代码块。
//
// 为什么需要生成器而不是手写：
//   1. NSIS 的 FileWrite 用双引号字符串，PowerShell 里的每个 $ 都要写成 $$，
//      每个 " 都要转义，手写 200 行几乎必然出错；
//   2. .ps1 与 hooks.nsh 两份文本一旦不同步就是静默故障 —— 安装时跑的是旧的
//      杀进程逻辑，而且没有任何报错。生成 + 校验可以让两者不可能漂移。
//
// 用法：node embed-kill-script.mjs            （打印代码块）
//       node embed-kill-script.mjs --check    （校验 hooks.nsh 里的是否还是最新的）

import fs from 'node:fs';
import path from 'node:path';

const HERE = path.dirname(new URL(import.meta.url).pathname.replace(/^\//, ''));
const PS1 = path.join(HERE, 'kill-app-tree.ps1');
const HOOKS = path.join(HERE, 'hooks.nsh');

const BEGIN = '  ; >>> BEGIN EMBEDDED kill-app-tree.ps1 (generated by installer/embed-kill-script.mjs — DO NOT EDIT BY HAND)';
const END = '  ; <<< END EMBEDDED kill-app-tree.ps1';

const raw = fs.readFileSync(PS1, 'utf8');

// 前置校验：改用 File 内嵌后，NSIS 的代码页/转义限制不再适用，
// 但 PowerShell 5.1 读取无 BOM 的 .ps1 时按系统 ANSI 代码页解码，
// 非 ASCII 会变乱码。脚本目前刻意保持 ASCII，这里继续守住这条约束。
const problems = [];
if (/[^\x00-\x7F]/.test(raw)) problems.push('脚本含非 ASCII 字符，PowerShell 5.1 会按 ANSI 代码页读成乱码');

if (problems.length) {
  for (const p of problems) console.error(`拒绝生成：${p}`);
  process.exit(1);
}

// v0.5.12: 不再用 FileWrite 逐行拼装，改用 File 内嵌原始文件。
//
// 为什么改（两条都是真机实测，不是推测）：
//
// 1) NSIS 的 FileWrite 字符串不做任何转义展开。
//    同一份 .nsi 里分别写 "A`r`nB" / "A\nB" / "A${NL}B" / "A$1B"，
//    落盘后全是字面量（反引号、\r、\n 原样保留），整个文件 0 个 CR、0 个 LF。
//    所以「每行末尾补换行符」这条路在本项目的 makensis 上走不通。
//
// 2) NSIS 的 FileOpen 无法用含正斜杠的路径**创建**文件
//    （IfFileExists 认正斜杠，所以「写完再查」会误判成没写成功）：
//      FileOpen 正斜杠写 + 反斜杠查 -> 读不到
//      FileOpen 反斜杠写 + 正斜杠查 -> 读得到（文件确实存在）
//      正斜杠写 + 正斜杠查(对照) -> 读不到
//      反斜杠写 + 反斜杠查(对照) -> 读得到
//
// 两个缺陷叠加的后果极其隐蔽：269 行的脚本塌成物理上的 1 行，
// <# 到 #> 的块注释在同一行闭合，PowerShell 于是什么都不执行，
// 退出码却是 0、stdout 为空、日志文件也不生成 —— 与「脚本根本没跑」
// 在 exit code 上完全无法区分，只有读落盘文件的字节才能看出来。
// 期间还因为 Node 侧物化器自己拼了换行，误判成「物化 269 行、语法通过」。
//
// File 是编译期内嵌 + 运行期原样解包：字节精确，不经过 ANSI 代码页转换，
// 不需要任何转义，也不受正斜杠影响，上面两类问题一起消失。
// ${__FILEDIR__} 在被 !include 的 .nsh 里指向本文件所在目录，
// 因此不必写死构建机的绝对路径。
const block = [
  BEGIN,
  '  ; kill-app-tree.ps1 由 makensis 在编译期内嵌，运行期原样解包到',
  '  ; $PLUGINSDIR。File 不经 ANSI 代码页转换，也不做任何转义，',
  '  ; 因此 269 行脚本能逐字节落盘 —— 这正是 FileWrite 方案做不到的。',
  `  File /oname=$PLUGINSDIR\\kill-app-tree.ps1 "\${__FILEDIR__}\\kill-app-tree.ps1"`,
  END,
].join('\n');

// --out 必须由 Node 自己写文件。不要用 PowerShell 的 `>` 重定向：
// Windows PowerShell 5.1 的重定向输出是 UTF-16LE（带 FF FE 头），
// Node 再按 UTF-8 读就会得到乱码，然后乱码会被原样写进 hooks.nsh。
const outIdx = process.argv.indexOf('--out');

if (outIdx !== -1) {
  const outPath = process.argv[outIdx + 1];

  if (!outPath) {
    console.error('--out 后面要给文件路径');
    process.exit(1);
  }

  fs.writeFileSync(outPath, `${block}\n`, 'utf8');
  console.log(`已写出 ${outPath}（UTF-8，${block.split('\n').length} 行）`);
  process.exit(0);
}

if (process.argv.includes('--sync')) {
  const hooks = fs.readFileSync(HOOKS, 'utf8');
  const start = hooks.indexOf(BEGIN);
  const end = hooks.indexOf(END);

  if (start === -1 || end === -1) {
    console.error('hooks.nsh 里找不到内嵌标记块，无法 --sync');
    process.exit(1);
  }

  const next = hooks.slice(0, start) + block + hooks.slice(end + END.length);
  fs.writeFileSync(HOOKS, next, 'utf8');
  console.log(`hooks.nsh 已同步（${block.split('\n').length} 行内嵌脚本）`);
  process.exit(0);
}

if (process.argv.includes('--check')) {
  const hooks = fs.readFileSync(HOOKS, 'utf8');
  const start = hooks.indexOf(BEGIN);
  const end = hooks.indexOf(END);

  if (start === -1 || end === -1) {
    console.error('漂移：hooks.nsh 里找不到内嵌标记块');
    process.exit(1);
  }

  const found = hooks.slice(start, end + END.length);

  if (found === block) {
    console.log('一致：hooks.nsh 内嵌的脚本与 kill-app-tree.ps1 同步');
    process.exit(0);
  }

  console.error('漂移：hooks.nsh 内嵌的脚本已过期，请运行 node embed-kill-script.mjs --sync');
  process.exit(1);
}

console.log(block);
